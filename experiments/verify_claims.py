"""Audit every hand-written quantitative claim against the actual run outputs.

The results sections of the writeup are generated by `fill_results.py` straight
from JSON, so they cannot drift. This script covers the parts a human wrote --
the abstract, README, RFC comment and theory file -- by recomputing each number
and diffing. Prior-work citations are listed at the end for manual re-check,
with the source each was taken from.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
RES = f"{ROOT}/results"
FAILED = []


def check(name, got, want, tol=0.02, unit=""):
    ok = want != 0 and abs(got - want) / abs(want) <= tol or (want == 0 and got == 0)
    print(f"  [{'OK ' if ok else 'FAIL'}] {name:<52} claimed {want}{unit}  actual {got:.4g}{unit}")
    if not ok:
        FAILED.append(name)


def main():
    print("== computable claims ==")

    # model sizes and ratio (README, paper Section 3)
    s0 = json.load(open(f"{RES}/stage0.json"))
    check("target params (M)", s0["target_params"] / 1e6, 1.87, 0.01)
    check("draft params (M)", s0["draft_params"] / 1e6, 0.27, 0.02)
    check("target/draft ratio", s0["target_params"] / s0["draft_params"], 6.9, 0.02, "x")
    check("base-model beta_0", s0["base_acceptance"]["beta_analytic"], 0.980, 0.005)
    check("base-model tokens/step", s0["base_acceptance"]["tokens_per_step_iid"], 4.80, 0.01)

    # source statistics (paper Section 3)
    import torch
    d = torch.load(f"{RES}/corpus.pt", weights_only=False)
    c = d["corpus"]
    cnt = torch.bincount(c.reshape(-1), minlength=256).float()
    pm = cnt / cnt.sum()
    check("unigram entropy (nats)", float(-(pm * pm.clamp_min(1e-12).log()).sum()), 4.40, 0.01)
    from tandemspec.data.synth import HMMSource
    src = torch.load(f"{RES}/sources.pt", weights_only=False)
    dom0 = HMMSource(*src["domains"][0])
    p0 = dom0.exact_predictive(c[d["dom_ids"] == 0][:32])
    check("Bayes-optimal conditional entropy (nats)",
          float(-(p0.clamp_min(1e-12).log() * p0).sum(-1).mean()), 2.99, 0.01)

    # serving memory arithmetic (README, RFC, abstract)
    from tandemspec.serving.paired_adapters import (AdapterSpec, module_shapes_from_hf_config)
    t = module_shapes_from_hf_config(4096, 14336, 32, 8, 32)
    dr = module_shapes_from_hf_config(2048, 8192, 16, 8, 32)
    tb = AdapterSpec("t", 32, t).n_bytes()
    db = AdapterSpec("d", 4, dr).n_bytes()
    check("task adapter MB/tenant (8B, r=32)", tb / 1e6, 168, 0.02, " MB")
    check("companion MB/tenant (1B drafter, r=4)", db / 1e6, 5.6, 0.02, " MB")
    check("companion overhead of adapter memory", 100 * db / tb, 3.4, 0.03, "%")
    check("companion vs private drafter", (1.24e9 * 2) / db, 440, 0.02, "x")

    # theory constants (theory.md, README, RFC)
    for gamma, want in ((4, 10.0), (8, 36.0)):
        check(f"dT/dbeta at gamma={gamma}", gamma * (gamma + 1) / 2, want, 0.001)

    # E1 headline (paper abstract / dashboard)
    if os.path.exists(f"{RES}/e1_acceptance_collapse.json"):
        e1 = json.load(open(f"{RES}/e1_acceptance_collapse.json"))["rows"]
        meta = json.load(open(f"{RES}/task_adapters.json"))
        kind = {int(k): v["kind"] for k, v in meta.items()}
        for k in ("in-dist", "held-out"):
            rs = [r for r in e1 if abs(r["strength"] - 1.0) < 1e-9 and kind[r["tenant"]] == k]
            b = sum(r["beta_analytic"] for r in rs) / len(rs)
            tk = sum(r["tokens_per_step_iid"] for r in rs) / len(rs)
            print(f"  [   ] {k+' tenants at s=1':<52} beta {b:.4f}, tokens/step {tk:.3f}")

    print("\n== simulator self-checks (re-running tests) ==")
    for t_ in ("test_accept.py", "test_theory.py", "test_paired_adapters.py"):
        r = subprocess.run([sys.executable, f"{ROOT}/tests/{t_}"], capture_output=True, text=True)
        print(f"  [{'OK ' if r.returncode == 0 else 'FAIL'}] {t_}")
        if r.returncode != 0:
            FAILED.append(t_)
            print(r.stdout[-800:], r.stderr[-800:])

    print("""
== prior-work citations (verified against the linked sources; re-check before publishing) ==
  arXiv:2607.12422  PEFT-BD 34.05+-0.20 vs FastMTP 188.01+-9.79 tok/s; accepted prefix
                    2.881 vs 1.511; draft 50.285 ms vs verify 50.621 ms; oracle ceiling 67.9 tok/s
  vLLM RFC #52038   drafter LoRA excludes lm_head/embed_tokens; ~28x size reduction vs 0.8B
                    drafters; quality within ~2%; opened 2026-08-12, one-week feedback window
  vLLM blog 2026-02 GPT-OSS 20B multi-LoRA: 171 OTPS / 124 ms TTFT, 8 adapters, rank 32
  vLLM blog 2026-05 EAGLE 3.1 on Kimi K2.6-NVFP4: 2x acceptance length vs EAGLE-3,
                    2.03x per-user output throughput at concurrency 1
  vLLM issue #13179 QLoRA supported offline only; not via the OpenAI-compatible server
""")
    print(f"RESULT: {'ALL CHECKS PASS' if not FAILED else 'FAILURES: ' + ', '.join(FAILED)}")
    return 1 if FAILED else 0


if __name__ == "__main__":
    sys.exit(main())
